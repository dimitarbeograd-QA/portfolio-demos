    desc = DESC.get(route) or (cut(sec["paras"][0], 155) if sec["paras"] else f"{title} – {SITE}. {GENERIC}")
    full_title = f"{title} | {SITE}"
    e = html.escape
    body = ([desc] if route in DESC else []) + ([] if route in NO_BODY else sec["paras"][:3])
    paras = "".join(f"<p>{e(cut(p, 380))}</p>" for p in body) or f"<p>{e(GENERIC)}</p>"
    docs = ""
    if sec["docs"]:
        docs = "<h2>Списък на документите</h2><ul>" + "".join(
            f'<li><a href="{e(h)}" rel="noopener">{e(l)}</a></li>' for h, l in sec["docs"] if l) + "</ul>"
    nav = "".join(
        f'<li><a href="../{p["route"]}/"{" aria-current=\"page\"" if p["route"] == route else ""}>{e(p["title"])}</a></li>'
        for p in pages)
    ld = (
        '{"@context":"https://schema.org","@graph":['
        f'{{"@type":"WebPage","@id":"{url}","url":"{url}","name":"{e(full_title)}","description":"{e(desc)}",'
        f'"inLanguage":"bg","isPartOf":{{"@type":"WebSite","name":"{SITE}","url":"{BASE}"}},"primaryImageOfPage":"{OG_IMAGE}"}},'
        f'{{"@type":"BreadcrumbList","itemListElement":[{{"@type":"ListItem","position":1,"name":"Начало","item":"{BASE}"}},'
        f'{{"@type":"ListItem","position":2,"name":"{e(title)}","item":"{url}"}}]}}]}}'
    )
