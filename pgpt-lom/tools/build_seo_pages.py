def main():
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    secs = sections(src)
    if not secs:
        sys.exit("no sub-pages found")
    logo = re.search(r'class="brand"[^>]*>\s*<img src="([^"]+)"', src).group(1)
    phone = "+359 888 98 48 96"
    mail = "pgpt@pgptlom.com"
    # remove stale generated folders (only those we created before)
    for f in ROOT.glob("*/index.html"):
        if f.parent.name not in ("img", "tools") and MARK in f.read_text(encoding="utf-8")[:200]:
            shutil.rmtree(f.parent)
    for s in secs:
        d = ROOT / s["route"]
        d.mkdir(exist_ok=True)
        (d / "index.html").write_text(page(s, secs, logo, phone, mail), encoding="utf-8")
    today = date.today().isoformat()
    urls = [(BASE, "1.0")] + [(f"{BASE}{s['route']}/", "0.7") for s in secs]
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{u}</loc><lastmod>{today}</lastmod><priority>{p}</priority></url>\n" for u, p in urls)
        + "</urlset>\n", encoding="utf-8")
    print(f"{len(secs)} pages + sitemap.xml")


if __name__ == "__main__":
    main()
