function randomInterests(i) {
  const n = 3 + (i % 4);
  const picked = new Set();
  let k = i * 7 + 3;
  while (picked.size < n) { picked.add(INTERESTS[k % INTERESTS.length]); k += 5; }
  return [...picked];
}


